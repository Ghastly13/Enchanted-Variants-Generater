using System;
using System.Collections.Generic;
using System.Text;
using Mutagen.Bethesda.Synthesis.Settings;

namespace EnchantedVariantsGenerator
{
    // The patcher's settings, edited on the patcher's Settings page in Synthesis and saved as settings.json in its data
    // folder. Property names are the JSON keys, the same as the old config.hjson, which is imported once if present.
    public class Config
    {
        [SynthesisOrder]
        [SynthesisSettingName("Reuse records from earlier runs")]
        [SynthesisTooltip("Keep the FormIDs of items and lists generated by an earlier run in the load order, updating them instead of making new ones.")]
        public bool CheckExistingGenerated { get; set; } = true;

        [SynthesisOrder]
        [SynthesisSettingName("Verbose logging")]
        [SynthesisTooltip("Log every enchantment, item and skipped duplicate as it is processed.")]
        public bool VerboseLogging { get; set; } = false;

        [SynthesisOrder]
        [SynthesisSettingName("Skip duplicates")]
        [SynthesisTooltip("Don't generate a variant when a playable one already exists with the same base item (template) and the same enchantment.")]
        public bool SkipDuplicates { get; set; } = true;

        [SynthesisOrder]
        [SynthesisSettingName("Distribute variants beside their vanilla twins")]
        [SynthesisTooltip("Hand the variants out as loot: each goes in a list of its own (<vanilla list>_EVG) added to the vanilla enchanted list its twin is in (e.g. SublistEnchArmorIronCuirass01, SublistEnchIronSwordFire), at the level that list gives the same tier, through a SkyPatcher INI applied after other mods'. Armor in a weight class vanilla never enchants for its material (light Daedric) follows that material's lists in the other class, placed in the matching lists for its own class. Ancient Nord weapons go in the Draugr loadout lists (LItemDraugr02BossWeapon1HMagic, ...), as vanilla's do. Anything drawing from the vanilla lists, Open World Loot included, then hands them out. Every placement is written to \"distributed items.txt\" in the patcher's data folder.")]
        public bool DistributeVariants { get; set; } = true;

        [SynthesisOrder]
        [SynthesisSettingName("Add skipped duplicates to leveled lists")]
        [SynthesisTooltip("Distribute the existing variant in place of the skipped one, when no leveled list holds it yet.")]
        public bool AddDuplicatesToLeveledLists { get; set; } = true;

        // Where the items and enchantments come from: the load order, the input files, or both (one item and enchantment
        // pair is made once either way)
        [SynthesisOrder]
        [SynthesisSettingName("Detect enchantments and items from the load order")]
        [SynthesisTooltip("Find the base weapons and armor in the load order (see \"Items: ...\") and give each the enchantments the load order already hands out on enchanted items of its kind, read from the vanilla enchanted lists its variants go in: an Iron sword gets what vanilla, Summermyst and Thaumaturgy put on Iron swords, at the same tier, charge and name. Light Daedric armor follows heavy Daedric; Ancient Nord weapons follow the Draugr loadout lists and the game's own Ancient Nord variants (frost, and fire on honed greatswords). Needs no input files. Every kind and its enchantments are listed in \"discovered items.txt\".")]
        public bool DetectEnchantments { get; set; } = true;

        [SynthesisOrder]
        [SynthesisSettingName("Use input files")]
        [SynthesisTooltip("Read the \"input\" folder in the patcher's data folder: every enchantment file in a subfolder applies to every weapon and armor file in it. With detection on as well, the input files add what detection does not make.")]
        public bool UseInputFiles { get; set; } = false;

        // JSON key kept from when this switched discovery itself on and off
        [SynthesisOrder]
        [SynthesisSettingName("Use input files: add found items to their folders")]
        [SynthesisTooltip("Add the base items found in the load order (see \"Items: ...\") that no input file names to the input folder for their type and tier, so they get that folder's enchantments too. Only with \"Use input files\" on.")]
        public bool DiscoverItems { get; set; } = true;

        [SynthesisOrder]
        [SynthesisSettingName("Items: excluded materials")]
        [SynthesisTooltip("Materials never found in the load order. Names: Iron, Steel, Imperial, Wood, Silver, PolishedSilver, Skyforge, Redguard, Akaviri, Forsworn, Dawnguard, Falmer, FalmerHoned, Draugr, DraugrHoned, NordHero, Orcish, Dwarven, Elven, Glass, Nordic, Ebony, Daedric, Stalhrim, Dragonbone, Amber, DarkSeducer, GoldenSaint, Madness, and the armor materials (e.g. Leather, Scaled, SteelPlate, Dragonplate). Every item found or left out, with the reason, is written to \"discovered items.txt\" in the patcher's data folder.")]
        public List<string> DiscoverExcludedMaterials { get; set; } = new()
        {
            "Imperial", "Wood", "Forsworn", "Silver", "Falmer", "FalmerHoned", "Dawnguard", "PolishedSilver", "Skyforge",
            "NordHero", "Redguard", "Akaviri", "Dragonbone", "Amber", "DarkSeducer", "GoldenSaint", "Madness",
        };

        [SynthesisOrder]
        [SynthesisSettingName("Items: excluded plugins")]
        [SynthesisTooltip("Plugins whose items are never found in the load order. Leave the base game in only when input files cover its items: with detection on, vanilla items get the enchantments other mods put on their kind (variants that already exist are skipped as duplicates).")]
        public List<string> DiscoverExcludedPlugins { get; set; } = new();

        [SynthesisOrder]
        [SynthesisSettingName("Items: include Creation Club items")]
        [SynthesisTooltip("Also find items from Creation Club plugins (cc....esm/.esl).")]
        public bool DiscoverCreationClub { get; set; } = false;

        [SynthesisOrder]
        [SynthesisSettingName("Items: excluded items")]
        [SynthesisTooltip("EditorIDs of items never found in the load order.")]
        public List<string> DiscoverExcludedItems { get; set; } = new();

        [SynthesisOrder]
        [SynthesisSettingName("Names: use SkyPatcher and Paths of Empyrean renames")]
        [SynthesisTooltip("Name items after the names they get at runtime from SkyPatcher INIs (e.g. WACCF's) and Paths of Empyrean's SKSE\\Plugins\\POE\\Weapon INIs, not only their plugin names.")]
        public bool ApplySkyPatcherNames { get; set; } = true;

        [SynthesisOrder]
        [SynthesisSettingName("Names: match enchantment names to the load order")]
        [SynthesisTooltip("Take each enchantment's prefix/suffix from the enchanted items that already exist for it: Thaumaturgy's naming when it is installed, else runtime renames (WACCF, Paths of Empyrean), else the most common spelling. The input file's Prefix/Suffix is used only when none exist.")]
        public bool MatchEnchantmentNames { get; set; } = true;

        // JSON key kept from when this only restored Thaumaturgy's names, so existing settings carry over
        [SynthesisOrder]
        [SynthesisSettingName("Names: fix names of existing enchanted items")]
        [SynthesisTooltip("Rename existing enchanted items (vanilla's and other mods') to match: the enchantment's load-order name around the base item's shown name, e.g. \"Ancient Nord Honed Sword of Frost\". Written as SkyPatcher INIs applied after other mods'. Items with unique names are left alone.")]
        public bool OverrideRuntimeEnchantmentNames { get; set; } = true;

        [SynthesisOrder]
        [SynthesisSettingName("Names: merge Paths of Empyrean and SkyPatcher renames")]
        [SynthesisTooltip("Where both rename an item, merge them (\"Ancient Nord Supple Shortbow\") and write the result to both, since their run order is unknown.")]
        public bool ReconcileRuntimeRenames { get; set; } = true;
    }

    public class InputJSON
    {
        public string[]? RequiredMods { get; set; }
        public ItemJSON[]? Armors { get; set; }
        public ItemJSON[]? Weapons { get; set; }
        public EnchantmentJSON[]? Enchantments { get; set; }
        public int PriorityOrder = 0;
    }

    public class ItemJSON
    {
        public string[]? RequiredMods { get; set; }
        public string[]? BlacklistedMods { get; set; }
        public string? FormKey { get; set; }
        public string? EditorID { get; set; }
        public uint? Value { get; set; }
        public bool SetScripts { get; set; } = true;
    }

    public class EnchantmentJSON
    {
        public string[]? RequiredMods { get; set; }
        public string? FormKey { get; set; }
        public string? EditorID { get; set; }
        public string? Prefix { get; set; }
        public string? Suffix { get; set; }
        public int? EnchantmentAmount { get; set; }
        public LeveledListInfo[]? LeveledLists { get; set; }
        public EnchantmentJSON[]? Overwrites { get; set; }
    }
}
